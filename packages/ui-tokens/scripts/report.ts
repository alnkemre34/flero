// Writes the measured contrast report to docs/architecture/evidence/contrast_report.md
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CHANGES, color, contrast, measureAll } from '../src/index.ts';

const rows = measureAll()
  .sort((a, b) => a.ratio / a.min - b.ratio / b.min)
  .map((m) => `| ${m.theme} | ${m.use} | ${m.ratio.toFixed(2)} | ${m.min} | ${m.pass ? 'pass' : '**FAIL**'} |`);
const failures = measureAll().filter((m) => !m.pass).length;
const hairline = (['light', 'dark'] as const).map((t) => `${t} ${contrast(color[t].hairline, color[t].surface).toFixed(2)}:1`).join(', ');

const md = `# Token contrast report (generated)

Generated by \`pnpm --filter @flero/ui-tokens report\` from \`packages/ui-tokens\`. Do not edit by hand.

- Requirement source: docs/architecture/14_PREMIUM_UI_UX_SYSTEM.md §12 (WCAG 2.2 AA: text ≥ 4.5:1, UI/focus ≥ 3:1)
- Pairs measured: ${measureAll().length}; failures: ${failures}
- Token changes forced by measurement: ${CHANGES.length === 0 ? 'none' : CHANGES.map((c) => `${c.token} ${c.from}→${c.to} (${c.reason})`).join('; ')}
- Sorted tightest-first (ratio ÷ minimum).

| Theme | Use | Ratio | Min | Result |
|---|---|---:|---:|---|
${rows.join('\n')}

**Informational (not a WCAG requirement as designed):** hairline vs surface is ${hairline}. The card is identified by its content and its tap target, not by the hairline border, so WCAG 1.4.11 doesn't apply to it. Any design that relies on the border alone to show a boundary must use \`textTertiary\` or a stronger color.

**Not covered by this report:** gradient frames (the Plus frame is decorative; the Plus pill text carries the meaning), image overlays, and rendered font antialiasing. On-device checks happen at M8 (G9).
`;

const out = fileURLToPath(new URL('../../../docs/architecture/evidence/contrast_report.md', import.meta.url));
writeFileSync(out, md);
console.log(`wrote ${out} (${failures} failures)`);
